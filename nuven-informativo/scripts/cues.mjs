/**
 * Cue sheet: the moments the picture and the sound react to, taken from the
 * real voice timings (content/timings.json, written by scripts/voice.py).
 *
 *   node scripts/cues.mjs   →  assets/cues.js   (window.NUVEN = { duration, scenes, cues, captions })
 *
 * The compositions load assets/cues.js, and scripts/music.mjs imports cues(),
 * so a counter starts on the exact word the narrator says and its ticks land
 * on the same frame. Re-run after `npm run voice`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function cues() {
  const t = JSON.parse(readFileSync(join(root, "content/timings.json"), "utf8"));
  const scene = Object.fromEntries(t.scenes.map((s) => [s.id, s]));
  /** start/end of the n-th word in a scene whose on-screen text starts with `text` */
  const word = (sceneId, text, n = 0) => {
    const hits = t.words.filter((w) => w.scene === sceneId && w.text.replace(/[¿?¡!.,;:]/g, "").startsWith(text));
    if (!hits[n]) throw new Error(`cue not found: ${sceneId} «${text}» #${n}`);
    return { start: hits[n].start, end: hits[n].end };
  };
  const c = {
    // 1 · gancho
    hookText: scene.gancho.vo_start,
    oneInSix: word("gancho", "1 de cada 6").start,
    // 2 · evolución
    bar2018: word("evolucion", "2018").start,
    count64: word("evolucion", "64").start,
    count83: word("evolucion", "83").start,
    label12: word("evolucion", "12").start,
    // 3 · los que quedan fuera
    ring28: word("fuera", "28").start,
    line34: word("fuera", "tercio").start,
    // 4 · por qué importa
    spain: word("importa", "España").start,
    seg37: word("importa", "37").start,
    toUSA: word("importa", "Estados").start,
    count97: word("importa", "97").start,
    impression: word("importa", "Cuando").start,
    impressionKey: word("importa", "primera").start,
    // 5 · qué aporta
    icons: [word("aporta", "Google").start, word("aporta", "credibilidad").start, word("aporta", "las 24 horas").start, word("aporta", "marca").start],
    // 6 · promoción
    logo: scene.promo.start + 0.15,
    tagline: word("promo", "diseñamos").start,
    cta: word("promo", "Hablemos").start,
  };
  return { duration: t.duration, scenes: t.scenes, cues: c, captions: t.captions, words: t.words };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const data = cues();
  const js = `// Generated by scripts/cues.mjs from content/timings.json — do not edit by hand.\nwindow.NUVEN = ${JSON.stringify(data)};\n`;
  writeFileSync(join(root, "assets/cues.js"), js);
  console.log(`✓ assets/cues.js · ${data.duration}s · ${Object.keys(data.cues).length} cues · ${data.captions.length} captions`);
}
