/**
 * Builds the two HyperFrames compositions from src/template.html and the cue
 * sheet (real voice timings):
 *
 *   index.html            16:9 · 1920×1080
 *   vertical/index.html   9:16 · 1080×1920 (assets/ is a symlink to ../assets)
 *
 * Scene clip times, subtitle cards and the root duration are written as static
 * data-* attributes so Studio, lint and the renderer all see the real timing.
 * Then the music bed is carved against the narration (HyperFrames voiceover
 * carve, /hyperframes-audio) and the same carve is copied to the vertical cut.
 *
 *   node scripts/build.mjs        (npm run build)
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { cues } from "./cues.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const data = cues();
writeFileSync(join(root, "assets/cues.js"), `// Generated by scripts/cues.mjs from content/timings.json — do not edit by hand.\nwindow.NUVEN = ${JSON.stringify(data)};\n`);

const S = Object.fromEntries(data.scenes.map((s) => [s.id, s]));
const order = ["gancho", "evolucion", "fuera", "importa", "aporta", "promo"];
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const r3 = (n) => Math.round(n * 1000) / 1000;

const STORE = (off) =>
  `<div class="store${off ? " off" : ""}"><svg viewBox="0 0 64 64" aria-hidden="true"><path d="M10 26 14 12h36l4 14" /><path d="M10 26c0 4 3 6 6.5 6S23 30 23 26c0 4 3 6 6.5 6s6.5-2 6.5-6c0 4 3 6 6.5 6s6.5-2 6.5-6" /><path d="M14 32v20h36V32" /><path d="M27 52V40h10v12" /></svg><span>${off ? "SIN WEB" : "CON WEB"}</span></div>`;
const STAR = `<svg viewBox="0 0 24 24" aria-hidden="true"><path d="m12 3.5 2.6 5.3 5.9.9-4.3 4.1 1 5.8L12 16.9l-5.2 2.7 1-5.8-4.3-4.1 5.9-.9z" /></svg>`;

/** subtitle cards; numbers (and the % sign) are bold so the key figure reads first */
const captions = data.captions
  .map((c) => {
    const html = esc(c.text).replace(/(\d+(?:[.,]\d+)?(?:\s?%)?(?: de cada \d+)?)/g, "<b>$1</b>");
    return `<div class="cap" data-in="${r3(c.start)}" data-out="${r3(c.end)}">${html}</div>`;
  })
  .join("\n        ");

function render(variant) {
  const v = variant === "v";
  let html = readFileSync(join(root, "src/template.html"), "utf8");
  const vars = {
    W: v ? 1080 : 1920,
    H: v ? 1920 : 1080,
    ORIENT: v ? "v" : "h",
    LABEL: v ? "9:16" : "16:9",
    ID: v ? "nuven-informativo-v" : "nuven-informativo",
    BASE: "",
    D: r3(data.duration),
    STORES: [0, 1, 2, 3, 4, 5].map((i) => STORE(i === 5)).join(""),
    CELLS: Array.from({ length: 100 }, () => `<i class="cell"></i>`).join(""),
    STARS: STAR.repeat(5),
    CAPTIONS: captions,
    LOCKUP_UP: v ? -260 : -150,
    WORDMARK: [..."NUVEN"].map((c) => `<span>${c}</span>`).join(""),
    WORDSUB: [..."DIGITAL"].map((c) => `<span>${c}</span>`).join(""),
    MUSIC_VOL: "0.6",
    SFX_VOL: "0.75",
    CARVE: "",
  };
  order.forEach((id, i) => {
    vars[`S${i + 1}_START`] = r3(S[id].start);
    vars[`S${i + 1}_DUR`] = r3(S[id].end - S[id].start);
  });
  html = html.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (!(k in vars)) throw new Error(`template variable ${k} has no value`);
    return String(vars[k]);
  });
  return html;
}

writeFileSync(join(root, "index.html"), render("h"));
mkdirSync(join(root, "vertical"), { recursive: true });
if (!existsSync(join(root, "vertical/assets"))) symlinkSync("../assets", join(root, "vertical/assets"));
writeFileSync(join(root, "vertical/index.html"), render("v"));

// ── voiceover carve on the music bed (same audio in both cuts) ──
const carve = join(homedir(), ".claude/skills/hyperframes-audio/scripts/carve.mjs");
if (existsSync(carve)) {
  execFileSync("node", [carve, "--comp", join(root, "index.html"), "--bed", "music", "--voice", "narration", "--strength", "0.7"], {
    cwd: root,
    stdio: ["ignore", "ignore", "inherit"],
  });
  // (Studio may stamp extra attributes such as data-hf-id, so match the tag by its id anywhere)
  const tag = /<audio\b[^>]*\bid="music"[^>]*><\/audio>/;
  const music = readFileSync(join(root, "index.html"), "utf8").match(tag)[0].replace(/ data-hf-id="[^"]*"/, "");
  const vpath = join(root, "vertical/index.html");
  writeFileSync(vpath, readFileSync(vpath, "utf8").replace(tag, music));
  console.log("✓ music bed carved against the narration (strength 0.7)");
} else {
  console.warn("! carve.mjs not found — run `npx hyperframes skills update hyperframes-audio`; the music is not ducked");
}
console.log(`✓ index.html (16:9) + vertical/index.html (9:16) · ${data.duration}s · ${data.captions.length} subtítulos`);
